"""Writes config/3v3_<Team>_roles.yaml (phase 1) and config/3v3_<Team>_coach.yaml (phase 2) for the three teams.
The six files are identical except for lambda, run ids and paths, so lambda stays the only difference
between the teams. Edit the settings here and run again rather than editing the YAML files by hand."""
TEAMS = {"NoPass": "0.0", "HalfPass": "0.5", "AllPass": "1.0"}
ROLES_STEPS = 300_000
COACH_STEPS = 1_000_000
COORDINATOR_STEPS = 70_000   # ~ the coach decisions (2 per second) made while the players train 1M steps

PLAYER = """  FootballAgent:
    trainer_type: ppo
    hyperparameters:
      batch_size: 256
      buffer_size: 4096
      learning_rate: 0.0003
      beta: 0.005
      epsilon: 0.2
      lambd: 0.95
      num_epoch: 3
      learning_rate_schedule: linear
    network_settings:         # must match the 3M models
      normalize: true
      hidden_units: 128
      num_layers: 2
    reward_signals:
      extrinsic:
        gamma: 0.995
        strength: 1.0
    init_path: {init}
    keep_checkpoints: 10
    checkpoint_interval: {ckpt}
    max_steps: {steps}
    time_horizon: 128
    summary_freq: 10000
    self_play:
      save_steps: 20000
      team_change: 100000     # the players' trainer decides when the learning team changes
      swap_steps: 2000
      window: 10
      play_against_latest_model_ratio: 0.5
      initial_elo: 1200.0
"""

COORDINATOR = """  Coordinator:                # the coach: picks a formation every 0.5 s; new network
    trainer_type: ppo
    hyperparameters:
      batch_size: 64
      buffer_size: 1024
      learning_rate: 0.0003
      beta: 0.01
      epsilon: 0.2
      lambd: 0.95
      num_epoch: 3
      learning_rate_schedule: linear
    network_settings:
      normalize: true
      hidden_units: 128
      num_layers: 2
    reward_signals:
      extrinsic:
        gamma: 0.99           # per coach decision (0.5 s)
        strength: 1.0
    keep_checkpoints: 10
    checkpoint_interval: 10000
    max_steps: {steps}
    time_horizon: 64
    summary_freq: 2000
    self_play:
      save_steps: 2000
      team_change: 100000000  # never: one learning-team switch is shared by all behaviors, the players' trainer drives it
      swap_steps: 200
      window: 10
      play_against_latest_model_ratio: 0.5
      initial_elo: 1200.0
"""

ENV = """environment_parameters:
  lambda: {lam}
  shaping_scale: 0.5          # the value the 3M runs ended on
  move_gain: 2.0              # the coach models' movement outputs were halved (tools/expand_for_coach.py)
  role_hold_weight: 6.0       # a whole match exactly on the slot earns 6 (a goal is worth 10-15)
  role_progress_weight: 0.1   # per metre moved towards the slot
  role_radius: 5.0            # in position = within 5 m of the slot
  spacing_weight: 0.0         # the spacing penalty is not used with the coach

env_settings:
  env_args: ["-coach", "{mode}"]

checkpoint_settings:
  run_id: {run}
"""

HEAD_ROLES = """# COACH STAGE, phase 1 "roles": Team {team} (lambda = {lam}).
# A scripted coach picks a random formation every 2-5 s; the players learn to follow their role
# (chaser goes for the ball, the others go to their slot), on top of their usual lambda rewards.
# Starts from the 3M model converted by tools/expand_for_coach.py (3 coach inputs, movement outputs halved).
# Generated by tools/make_coach_configs.py.  Run: .\train_3v3.ps1 -Stage roles
"""
HEAD_COACH = """# COACH STAGE, phase 2 "coach": Team {team} (lambda = {lam}).
# A learning coach (behavior "Coordinator", one per team) picks the formation every 0.5 s from the whole
# match state and is rewarded on the team result. The players keep their own policies and their own
# lambda-weighted rewards, and continue from phase 1.
# Generated by tools/make_coach_configs.py.  Run: .\train_3v3.ps1 -Stage coach
"""

for team, lam in TEAMS.items():
    roles = (HEAD_ROLES.format(team=team, lam=lam) + "behaviors:\n"
             + PLAYER.format(init=f"results/3v3_{team}_coachbase/FootballAgent/checkpoint.pt", ckpt=50000, steps=ROLES_STEPS)
             + "\n" + ENV.format(lam=lam, mode="scripted", run=f"3v3_{team}_roles"))
    coach = (HEAD_COACH.format(team=team, lam=lam) + "behaviors:\n"
             + PLAYER.format(init=f"results/3v3_{team}_roles/FootballAgent/checkpoint.pt", ckpt=100000, steps=COACH_STEPS)
             + COORDINATOR.format(steps=COORDINATOR_STEPS)
             + "\n" + ENV.format(lam=lam, mode="learned", run=f"3v3_{team}_coach"))
    open(f"config/3v3_{team}_roles.yaml", "w", newline="\n").write(roles)
    open(f"config/3v3_{team}_coach.yaml", "w", newline="\n").write(coach)
    print("wrote", f"config/3v3_{team}_roles.yaml", f"config/3v3_{team}_coach.yaml")
