"""Writes, for the three teams: config/3v3_<Team>_roles.yaml (phase 1), config/3v3_<Team>_coach.yaml (phase 2), and the
two phase-3 continuations of phase 2: config/3v3_<Team>_coach2.yaml (same rules) and
config/3v3_<Team>_coach2nopress.yaml (the coach may not pick Press). The files are identical except for lambda, run ids and paths, so lambda stays the only difference
between the teams. Edit the settings here and run again rather than editing the YAML files by hand."""
TEAMS = {"NoPass": "0.0", "HalfPass": "0.5", "AllPass": "1.0"}
ROLES_STEPS = 300_000
COACH_STEPS = 1_000_000
COORDINATOR_STEPS = 20_000   # ~11k coach decisions happen while the players train 1M steps (15-22 decisions per
                             # match); the remaining ~9k are coach-only, with the players fixed at their final policy

PLAYER = """  FootballAgent:
    trainer_type: ppo
    hyperparameters:
      batch_size: 256
      buffer_size: 4096
      learning_rate: 0.0003
      beta: 0.005
      epsilon: 0.2
      lambd: 0.95
      num_epoch: 3
      learning_rate_schedule: linear
    network_settings:         # must match the 3M models
      normalize: true
      hidden_units: 128
      num_layers: 2
    reward_signals:
      extrinsic:
        gamma: 0.995
        strength: 1.0
    init_path: {init}
    keep_checkpoints: 10
    checkpoint_interval: {ckpt}
    max_steps: {steps}
    time_horizon: 128
    summary_freq: 10000
    self_play:
      save_steps: 20000
      team_change: 100000     # the players' trainer decides when the learning team changes
      swap_steps: 2000
      window: 10
      play_against_latest_model_ratio: 0.5
      initial_elo: 1200.0
"""

COORDINATOR = """  Coordinator:                # the coach: picks a formation at each decision point
    trainer_type: ppo
{init}    hyperparameters:          # small-data settings: ~20k decisions in total
      batch_size: 64
      buffer_size: 512
      learning_rate: 0.0003
      beta: 0.005
      epsilon: 0.2
      lambd: 0.95
      num_epoch: 4
      learning_rate_schedule: linear
    network_settings:
      normalize: true
      hidden_units: 128
      num_layers: 2
    reward_signals:
      extrinsic:
        gamma: 0.95           # per decision (~3 s): looks ahead about one match
        strength: 1.0
    keep_checkpoints: 10
    checkpoint_interval: 2000
    max_steps: {steps}
    time_horizon: 64
    summary_freq: 1000
    self_play:
      save_steps: 1000
      team_change: 100000000  # never: one learning-team switch is shared by all behaviors, the players' trainer drives it
      swap_steps: 100
      window: 10
      play_against_latest_model_ratio: 0.5
      initial_elo: 1200.0
"""

ENV = """environment_parameters:
  lambda: {lam}
  shaping_scale: 0.5          # the value the 3M runs ended on
  move_gain: 2.0              # the coach models' movement outputs were halved (tools/expand_for_coach.py)
  role_hold_weight: {hold}       # role rewards: 0 from coach3 on (see HEAD_CLEAN); earlier stages used 6 / 0.1
  role_progress_weight: {prog}
  role_radius: 5.0            # in position = within 5 m of the slot
  spacing_weight: 0.0         # the spacing penalty is not used with the coach
  coach_decision_period: 3.0  # formation decisions: kick-off, possession switch, otherwise every 3 s
  coach_min_gap: 1.0          # never two formation decisions less than 1 s apart
  coach_territory_weight: 0.1 # coach reward per metre the ball moves towards the opponent goal (zero-sum)
  coach_allow_press: {press}        # 1 = allowed; 0 = the coach may not pick Press (action masking)

env_settings:
  env_args: ["-coach", "{mode}"]

checkpoint_settings:
  run_id: {run}
"""

HEAD_ROLES = """# COACH STAGE, phase 1 "roles": Team {team} (lambda = {lam}).
# A scripted coach picks a RANDOM formation at each decision point; the players learn to follow their role
# (chaser goes for the ball, the others go to their slot), on top of their usual lambda rewards.
# Starts from the 3M model converted by tools/expand_for_coach.py (3 coach inputs, movement outputs halved,
# slot prior). Note: the 3v3_<Team>_roles runs of 2026-11-16 were made with the first coach timing (a new
# random formation every 2-5 s); the scripted coach now uses the same decision points as the learned one.
# Generated by tools/make_coach_configs.py.  Run: train_3v3.ps1 -Stage roles
"""
HEAD_COACH = """# COACH STAGE, phase 2 "coach": Team {team} (lambda = {lam}).
# A learning coach (behavior "Coordinator", one per team) picks the formation at kick-off, on a possession
# switch and otherwise every 3 s, from the whole match state; rewarded on the team result (goals +-, and
# territory gained). The players keep their own policies and their own
# lambda-weighted rewards, and continue from phase 1.
# Generated by tools/make_coach_configs.py.  Run: train_3v3.ps1 -Stage coach
"""
HEAD_CONT = """# COACH STAGE, phase 3 "{stage}": Team {team} (lambda = {lam}).
# Continues phase 2 (players AND coach start from results/3v3_{team}_coach) for another 1M player steps and
# 20k coach decisions, with the same rules{note}
# Generated by tools/make_coach_configs.py.  Run: train_3v3.ps1 -Stage {stage}
"""
NOPRESS_NOTE = """, EXCEPT that the coach may not pick Press (masked).
# In phase 2 the coaches drifted towards Press (AllPass 78%), which pulls the supporting players back next
# to the ball; without it every formation the coach can pick keeps them spread out."""

HEAD_CLEAN = """# COACH STAGE "{stage}" (clean rewards): Team {team} (lambda = {lam}).
# {what}
# PLAYERS' REWARD = exactly the original lambda reward (role_hold_weight = role_progress_weight = 0): the coach
# only gives information (3 inputs + the slot prior in the network). Why: the role rewards could be farmed.
# Holding a slot paid an income per second, and "move closer to your slot" skipped the step when the slot
# jumped, so players earned ~13 per match walking back to slots after every formation change while nobody
# played the ball (2026-11-17: HalfPass, then AllPass, 0 passes and 0 goals; see the *_coach2nopress_flawed runs).
# Without role rewards the spacing held (8-10 m) and play recovered, identically tested on all three teams.
# The coach is rewarded as before (goals +-, territory). Identical for all three teams except lambda.
# Generated by tools/make_coach_configs.py.  Run: train_3v3.ps1 -Stage {stage}
"""
FLAWED_NOTE = """# NOTE: trained with role rewards that turned out to be farmable (see config/3v3_<Team>_coach3.yaml).
"""

NL = "\n"
OLD_ROLE = dict(hold=6.0, prog=0.1)     # what phase 1 / phase 2 v2 were trained with
NO_ROLE = dict(hold=0.0, prog=0.0)

for team, lam in TEAMS.items():
    roles = (HEAD_ROLES.format(team=team, lam=lam) + FLAWED_NOTE + "behaviors:" + NL
             + PLAYER.format(init=f"results/3v3_{team}_coachbase/FootballAgent/checkpoint.pt", ckpt=50000, steps=ROLES_STEPS)
             + NL + ENV.format(lam=lam, mode="scripted", run=f"3v3_{team}_roles", press=1, **OLD_ROLE))
    coach = (HEAD_COACH.format(team=team, lam=lam) + FLAWED_NOTE + "behaviors:" + NL
             + PLAYER.format(init=f"results/3v3_{team}_roles/FootballAgent/checkpoint.pt", ckpt=100000, steps=COACH_STEPS)
             + COORDINATOR.format(steps=COORDINATOR_STEPS, init="")
             + NL + ENV.format(lam=lam, mode="learned", run=f"3v3_{team}_coach", press=1, **OLD_ROLE))
    files = {f"config/3v3_{team}_roles.yaml": roles, f"config/3v3_{team}_coach.yaml": coach}
    for stage, press in (("coach2", 1), ("coach2nopress", 0)):
        files[f"config/3v3_{team}_{stage}.yaml"] = (
            HEAD_CONT.format(stage=stage, team=team, lam=lam, note="." if press else NOPRESS_NOTE) + FLAWED_NOTE
            + "behaviors:" + NL
            + PLAYER.format(init=f"results/3v3_{team}_coach/FootballAgent/checkpoint.pt", ckpt=100000, steps=COACH_STEPS)
            + COORDINATOR.format(steps=COORDINATOR_STEPS,
                                 init=f"    init_path: results/3v3_{team}_coach/Coordinator/checkpoint.pt" + NL)
            + NL + ENV.format(lam=lam, mode="learned", run=f"3v3_{team}_{stage}", press=press, **OLD_ROLE))

    # Clean-reward stages
    files[f"config/3v3_{team}_coach3.yaml"] = (
        HEAD_CLEAN.format(stage="coach3", team=team, lam=lam,
                          what="Phase 2 redone: players start from phase 1 (results/3v3_{0}_roles), a NEW coach; "
                               "1M player steps + 20k coach decisions.".format(team))
        + "behaviors:" + NL
        + PLAYER.format(init=f"results/3v3_{team}_roles/FootballAgent/checkpoint.pt", ckpt=100000, steps=COACH_STEPS)
        + COORDINATOR.format(steps=COORDINATOR_STEPS, init="")
        + NL + ENV.format(lam=lam, mode="learned", run=f"3v3_{team}_coach3", press=1, **NO_ROLE))
    for stage, press, what in (
            ("coach3b", 1, "Continues coach3 (players and coach) for +1M player steps and +20k coach decisions."),
            ("coach3nopress", 0, "Continues coach3 (players and coach) for +1M / +20k, but the coach may not pick "
                                 "Press (masked), so every formation keeps the supporting players spread out.")):
        files[f"config/3v3_{team}_{stage}.yaml"] = (
            HEAD_CLEAN.format(stage=stage, team=team, lam=lam, what=what)
            + "behaviors:" + NL
            + PLAYER.format(init=f"results/3v3_{team}_coach3/FootballAgent/checkpoint.pt", ckpt=100000, steps=COACH_STEPS)
            + COORDINATOR.format(steps=COORDINATOR_STEPS,
                                 init=f"    init_path: results/3v3_{team}_coach3/Coordinator/checkpoint.pt" + NL)
            + NL + ENV.format(lam=lam, mode="learned", run=f"3v3_{team}_{stage}", press=press, **NO_ROLE))
    for path, text in files.items():
        with open(path, "w", newline=NL) as f:
            f.write(text)
        print("wrote", path)
